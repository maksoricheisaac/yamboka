export function isDisposableEmail(email: string): boolean {
  const domain = email.split('@')[1]?.toLowerCase();
  if (!domain) return false;
  // Refuse aussi les sous-domaines d'un domaine listé.
  return domain
    .split('.')
    .some((_, i, parts) => DISPOSABLE_DOMAINS.has(parts.slice(i).join('.')));
}
